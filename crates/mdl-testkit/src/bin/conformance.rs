//! Writes the generated decoding cases of `conformance/decoding/oracle/`
//! (`spec/conformance.md` §2.3), or of the directory given: a fixed sample
//! of the oracle's layouts, each from a seed of its own, so running it
//! again with the same testkit and proptest writes the same files. The
//! files are a snapshot: regenerate them on purpose, and review the diff.
//! `just conformance` runs it, as
//! `cargo run -p mdl-testkit --bin conformance [dir]`.

use std::error::Error;
use std::fs;
use std::path::{Path, PathBuf};

use mdl_testkit::conformance::case_file;
use mdl_testkit::layout::{self, Telemetry};
use proptest::strategy::{BoxedStrategy, Strategy, ValueTree};
use proptest::test_runner::{Config, RngAlgorithm, TestRng, TestRunner};

/// Each kind of file: its name, the generator, how many layouts, and what
/// its files hold.
fn kinds() -> Vec<(&'static str, BoxedStrategy<Telemetry>, usize, &'static str)> {
    vec![
        (
            "binary",
            layout::telemetry(),
            24,
            "a binary layout as layout::telemetry() makes it, and its messages",
        ),
        (
            "binary-damaged",
            layout::damaged(),
            24,
            "a binary layout as layout::damaged() makes it, and its messages, faults planted in most of them",
        ),
        (
            "json",
            layout::json_telemetry(),
            12,
            "a JSON layout as layout::json_telemetry() makes it, and its messages",
        ),
        (
            "json-damaged",
            layout::json_damaged(),
            12,
            "a JSON layout as layout::json_damaged() makes it, and its messages, faults planted in most of them",
        ),
    ]
}

fn main() -> Result<(), Box<dyn Error>> {
    let dir = std::env::args().nth(1).map_or_else(
        || PathBuf::from("conformance/decoding/oracle"),
        PathBuf::from,
    );
    fs::create_dir_all(&dir)?;
    let kinds = kinds();
    remove_written(&dir, &kinds)?;
    let mut cases = 0;
    for (kind, strategy, count, holds) in &kinds {
        for index in 0..*count {
            let mut runner = TestRunner::new_with_rng(
                Config::default(),
                TestRng::from_seed(RngAlgorithm::ChaCha, &seed(kind, index)),
            );
            let telemetry = strategy
                .new_tree(&mut runner)
                .map_err(|reason| format!("{kind} {index}: {reason}"))?
                .current();
            let origin = format!("{kind} seed {index}");
            let about = format!(
                "Generated by the testkit's oracle (crates/mdl-testkit, {origin}): {holds}, each with \
                 the result or error the oracle works out forward from decoding.md, in code separate \
                 from MDL's decoder; spec/conformance.md section 2.3 says what that does and doesn't \
                 check."
            );
            let file = case_file(&telemetry, &about, &origin);
            cases += file["cases"].as_array().map_or(0, Vec::len);
            let path = dir.join(format!("{kind}-{index:02}.json"));
            fs::write(&path, serde_json::to_string_pretty(&file)? + "\n")?;
        }
    }
    println!("wrote {cases} cases to {}", dir.display());
    Ok(())
}

/// A layout's seed: its kind's name, then its index.
fn seed(kind: &str, index: usize) -> [u8; 32] {
    let mut seed = [0; 32];
    let name = kind.as_bytes();
    let length = name.len().min(24);
    seed[..length].copy_from_slice(&name[..length]);
    seed[24..].copy_from_slice(&(index as u64).to_le_bytes());
    seed
}

/// Removes the files an earlier run wrote, so a smaller sample leaves none
/// behind: only names of the kinds' own pattern, `<kind>-<nn>.json`.
fn remove_written(
    dir: &Path,
    kinds: &[(&'static str, BoxedStrategy<Telemetry>, usize, &'static str)],
) -> Result<(), Box<dyn Error>> {
    for entry in fs::read_dir(dir)? {
        let path = entry?.path();
        let Some(name) = path.file_name().and_then(|name| name.to_str()) else {
            continue;
        };
        let written = kinds.iter().any(|(kind, ..)| {
            name.strip_prefix(kind)
                .and_then(|rest| rest.strip_prefix('-'))
                .and_then(|rest| rest.strip_suffix(".json"))
                .is_some_and(|number| {
                    number.len() == 2 && number.bytes().all(|b| b.is_ascii_digit())
                })
        });
        if written {
            fs::remove_file(&path)?;
        }
    }
    Ok(())
}
