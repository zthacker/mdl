//! Decoding conformance cases (`spec/conformance.md` §2) written from the
//! oracle's layouts: each message of a generated [`Telemetry`], with what
//! [`crate::layout`] works out it decodes to, spelled as `spec/api.md` §1
//! and §3.1 spell a result. This module spells them itself, never through
//! `mdl`, so a case says what the oracle read in the spec, not what the
//! runtime gives.

use std::collections::BTreeSet;

use serde_json::{Map, Value, json};

use crate::layout::{
    Damage, Encoding, Engineering, EventTime, Expected, Message, Meta, Raw, Sample, Telemetry,
    instant_text, integer_json,
};

/// The largest integer JSON writes as a number (`spec/api.md` §1).
const MAX_SAFE: i128 = (1 << 53) - 1;

/// The asset the case file's one binding names.
const ASSET: &str = "ASSET";

/// A case file for `telemetry`: its bundle, a binding of its native id to
/// its set, and a case for each message a case can hold. It can't hold
/// one delivered in the encoding other than its family's, since an API
/// types each payload by its family (`spec/api.md` §2.2), nor one with a
/// metadata name given twice, since a case's metadata is an object, which
/// has each name once (`spec/decoding.md` §1). `about` says where the
/// layout came from; each case's note names it again (`origin`) with the
/// message's place in it.
pub fn case_file(telemetry: &Telemetry, about: &str, origin: &str) -> Value {
    let json_family = telemetry.bundle["families"][0]["encoding"] == "json";
    let family_encoding = if json_family {
        Encoding::Json
    } else {
        Encoding::Binary
    };
    let cases: Vec<Value> = telemetry
        .messages
        .iter()
        .enumerate()
        .filter(|(_, message)| {
            message.encoding == family_encoding && !repeats_a_name(&message.metadata)
        })
        .map(|(index, message)| case(telemetry, message, index, json_family, origin))
        .collect();
    json!({
        "about": about,
        "definitions": telemetry.bundle,
        "bindings": bindings(telemetry),
        "cases": cases,
    })
}

/// Whether a metadata name is given more than once.
fn repeats_a_name(metadata: &[(String, Meta)]) -> bool {
    let mut names = BTreeSet::new();
    metadata.iter().any(|(name, _)| !names.insert(name))
}

/// The bindings file the property tests decode the layout's messages
/// with, as its lines: the native id bound to the set from the GPS epoch
/// on, before any generated ground time.
fn bindings(telemetry: &Telemetry) -> Vec<String> {
    let native_id = match integer_spelled(&telemetry.native_id) {
        Some(n) if n.abs() <= MAX_SAFE => n.to_string(),
        _ => Value::from(telemetry.native_id.as_str()).to_string(),
    };
    vec![
        "mdl_version = \"2.0\"".to_string(),
        String::new(),
        "[[binding]]".to_string(),
        format!("family = {}", Value::from(telemetry.family.as_str())),
        format!("native_id = {native_id}"),
        format!("asset = {}", Value::from(ASSET)),
        format!("set = {}", Value::from(telemetry.set.as_str())),
        "effective_from = \"1980-01-06T00:00:00Z\"".to_string(),
    ]
}

fn case(
    telemetry: &Telemetry,
    message: &Message,
    index: usize,
    json_family: bool,
    origin: &str,
) -> Value {
    let mut note = format!(
        "Generated by the testkit's oracle: {origin}, message {index}, of packet {}.",
        message.packet
    );
    let (spec, outcome) = match &message.damage {
        Some(Damage {
            planted, failure, ..
        }) => {
            note.push_str(&format!(" Planted: {planted}."));
            (
                damaged_spec(json_family),
                ("error", json!(failure.problem.code())),
            )
        }
        None if message.event_time == EventTime::Invalid => {
            note.push_str(" Its event time can't be read.");
            (damaged_spec(json_family), ("error", json!("invalid_time")))
        }
        None => (
            decoded_spec(json_family),
            ("decoded", decoded(telemetry, message)),
        ),
    };
    let payload = match std::str::from_utf8(&message.payload) {
        Ok(text) if json_family => ("json", json!(text)),
        _ => ("hex", json!(hex(&message.payload))),
    };
    let metadata: Map<String, Value> = message
        .metadata
        .iter()
        .map(|(name, value)| {
            let value = match value {
                Meta::Uint(n) => integer_json(i128::from(*n)),
                Meta::Int(n) => integer_json(i128::from(*n)),
                Meta::Text(text) => json!(text),
            };
            (name.clone(), value)
        })
        .collect();
    let mut message_json = Map::new();
    message_json.insert(payload.0.to_string(), payload.1);
    message_json.insert("metadata".to_string(), Value::Object(metadata));
    message_json.insert(
        "ground_time".to_string(),
        json!(instant_text(message.received)),
    );
    let mut case = Map::new();
    case.insert(
        "name".to_string(),
        json!(format!("{index:02}-{}", message.packet)),
    );
    case.insert("spec".to_string(), json!(spec));
    case.insert("note".to_string(), json!(note));
    case.insert("family".to_string(), json!(telemetry.family));
    case.insert("message".to_string(), Value::Object(message_json));
    case.insert(outcome.0.to_string(), outcome.1);
    Value::Object(case)
}

/// The sections a message's result depends on: its values, routing,
/// identification, extraction (checksums included), record, meaning and
/// event time.
fn decoded_spec(json_family: bool) -> Vec<&'static str> {
    let values = if json_family {
        &["decoding.md §2.3"][..]
    } else {
        &["decoding.md §2.1", "decoding.md §2.2"][..]
    };
    let mut spec = values.to_vec();
    spec.extend([
        "decoding.md §3",
        "decoding.md §4",
        "decoding.md §5",
        "decoding.md §6",
        "decoding.md §7",
        "decoding.md §8",
        "api.md §3.1",
    ]);
    spec
}

/// The sections an error depends on: routing, identification,
/// extraction, event time and the codes.
fn damaged_spec(json_family: bool) -> Vec<&'static str> {
    let mut spec = if json_family {
        vec!["decoding.md §2.3"]
    } else {
        vec!["decoding.md §2.1", "decoding.md §2.2"]
    };
    spec.extend([
        "decoding.md §3",
        "decoding.md §4",
        "decoding.md §5",
        "decoding.md §8",
        "decoding.md §9",
    ]);
    spec
}

/// The decoded message `spec/api.md` §3.1 gives, without `def_version`.
fn decoded(telemetry: &Telemetry, message: &Message) -> Value {
    json!({
        "family": telemetry.family,
        "native_id": native_id(&telemetry.native_id),
        "asset": ASSET,
        "stand_in": false,
        "set": telemetry.set,
        "packet": message.packet,
        "event_time": event_time(&message.event_time, message.received),
        "samples": message
            .samples
            .iter()
            .map(|sample| sample_json(sample, &telemetry.bundle))
            .collect::<Vec<Value>>(),
        "record": record_json(&message.record),
        "engineering": message
            .engineering
            .iter()
            .map(engineering_json)
            .collect::<Vec<Value>>(),
    })
}

/// A native id (`spec/api.md` §1): the integer its text spells in its one
/// decimal spelling within -2^63 to 2^64 - 1, as JSON writes an integer;
/// any other text as it is.
fn native_id(text: &str) -> Value {
    match integer_spelled(text) {
        Some(n) => integer_json(n),
        None => json!(text),
    }
}

/// The integer `text` spells in its one decimal spelling (no sign but a
/// leading `-`, no leading zeros, not `-0`), within -2^63 to 2^64 - 1.
fn integer_spelled(text: &str) -> Option<i128> {
    let digits = text.strip_prefix('-').unwrap_or(text);
    let one_spelling = !digits.is_empty()
        && digits.bytes().all(|byte| byte.is_ascii_digit())
        && (digits == "0" || !digits.starts_with('0'))
        && text != "-0";
    if !one_spelling {
        return None;
    }
    let n: i128 = text.parse().ok()?;
    (-(1_i128 << 63)..=(1_i128 << 64) - 1)
        .contains(&n)
        .then_some(n)
}

fn event_time(time: &EventTime, received: i128) -> Value {
    match time {
        EventTime::Ground => json!({ "kind": "ground", "time": instant_text(received) }),
        EventTime::At(at) => json!({ "kind": "at", "time": instant_text(*at) }),
        EventTime::SinceBoot { value, unit } => {
            json!({ "kind": "since_boot", "value": integer_json(i128::from(*value)), "unit": unit })
        }
        // A message whose event time can't be read is an error case.
        EventTime::Invalid => Value::Null,
    }
}

/// A sample (`spec/api.md` §3.1), with its param's unit from the catalog.
fn sample_json(sample: &Sample, bundle: &Value) -> Value {
    let unit = bundle["catalog"]["params"][&sample.param]
        .get("unit")
        .cloned()
        .unwrap_or(Value::Null);
    json!({
        "param": sample.param,
        "value": expected_json(&sample.value),
        "unit": unit,
        "path": sample.path,
        "index": sample.index.map(|index| integer_json(i128::from(index))),
        "time_offset_ns": sample.time_offset_ns.map(|ns| integer_json(i128::from(ns))),
        "quality": sample.quality,
    })
}

fn engineering_json(engineering: &Engineering) -> Value {
    json!({
        "path": engineering.path,
        "value": expected_json(&engineering.value),
        "quality": engineering.quality,
    })
}

/// A record (`spec/api.md` §3.1): each present entry by name.
fn record_json(record: &[(String, Raw)]) -> Value {
    Value::Object(
        record
            .iter()
            .map(|(name, raw)| (name.clone(), raw_json(raw)))
            .collect(),
    )
}

/// A raw value in `spec/api.md` §1's spelling.
fn raw_json(raw: &Raw) -> Value {
    match raw {
        Raw::Uint(n) => integer_json(i128::from(*n)),
        Raw::Int(n) => integer_json(i128::from(*n)),
        Raw::Float(x) => float_json(*x),
        Raw::Bool(b) => json!(b),
        Raw::Str(text) => json!(text),
        Raw::Bytes(bytes) => json!(hex(bytes)),
        Raw::Array(items) => Value::Array(items.iter().map(raw_json).collect()),
        Raw::Record(fields) => record_json(fields),
        Raw::Null => Value::Null,
    }
}

/// A sample's or engineering value in `spec/api.md` §1's spelling: a
/// vector as its frame and members, a quaternion scalar first.
fn expected_json(value: &Expected) -> Value {
    match value {
        Expected::F64(x) => float_json(*x),
        Expected::I64(n) => integer_json(i128::from(*n)),
        Expected::U64(n) => integer_json(i128::from(*n)),
        Expected::Bool(b) => json!(b),
        Expected::Str(text) | Expected::Enum(text) => json!(text),
        Expected::Bytes(bytes) => json!(hex(bytes)),
        Expected::Vector { frame, members } => {
            let mut vector = Map::new();
            vector.insert("frame".to_string(), json!(frame));
            let names: &[&str] = if members.len() == 4 {
                &["w", "x", "y", "z"]
            } else {
                &["x", "y", "z"]
            };
            for (name, member) in names.iter().zip(members) {
                vector.insert((*name).to_string(), float_json(*member));
            }
            Value::Object(vector)
        }
    }
}

/// A float: a JSON number for a finite one, which serde_json writes with
/// a fraction or an exponent, so it reads back as a float; NaN and the
/// infinities as `spec/api.md` §1's objects.
fn float_json(x: f64) -> Value {
    if x.is_nan() {
        json!({ "non_finite": "NaN" })
    } else if x == f64::INFINITY {
        json!({ "non_finite": "inf" })
    } else if x == f64::NEG_INFINITY {
        json!({ "non_finite": "-inf" })
    } else {
        json!(x)
    }
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}
