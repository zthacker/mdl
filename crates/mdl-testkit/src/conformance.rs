fn damaged_spec(json_family: bool) -> Vec<&'static str> {
    let mut spec = if json_family {
        vec!["decoding.md §2.3"]
    } else {
        vec!["decoding.md §2.1", "decoding.md §2.2"]
    };
    spec.extend([
        "decoding.md §3",
        "decoding.md §4",
        "decoding.md §5",
        "decoding.md §8",
        "decoding.md §9",
    ]);
    spec
}

/// The decoded message `spec/api.md` §3.1 gives, without `def_version`.
fn decoded(telemetry: &Telemetry, message: &Message) -> Value {
    json!({
        "family": telemetry.family,
        "native_id": native_id(&telemetry.native_id),
        "asset": ASSET,
        "stand_in": false,
        "set": telemetry.set,
        "packet": message.packet,
        "event_time": event_time(&message.event_time, message.received),
        "samples": message
            .samples
            .iter()
            .map(|sample| sample_json(sample, &telemetry.bundle))
            .collect::<Vec<Value>>(),
        "record": record_json(&message.record),
        "engineering": message
            .engineering
            .iter()
            .map(engineering_json)
            .collect::<Vec<Value>>(),
    })
}

/// A native id (`spec/api.md` §1): the integer its text spells in its one
/// decimal spelling within -2^63 to 2^64 - 1, as JSON writes an integer;
/// any other text as it is.
fn native_id(text: &str) -> Value {
    match integer_spelled(text) {
        Some(n) => integer_json(n),
        None => json!(text),
    }
}

/// The integer `text` spells in its one decimal spelling (no sign but a
/// leading `-`, no leading zeros, not `-0`), within -2^63 to 2^64 - 1.
fn integer_spelled(text: &str) -> Option<i128> {
    let digits = text.strip_prefix('-').unwrap_or(text);
    let one_spelling = !digits.is_empty()
        && digits.bytes().all(|byte| byte.is_ascii_digit())
        && (digits == "0" || !digits.starts_with('0'))
        && text != "-0";
    if !one_spelling {
        return None;
    }
    let n: i128 = text.parse().ok()?;
    (-(1_i128 << 63)..=(1_i128 << 64) - 1)
        .contains(&n)
        .then_some(n)
}

fn event_time(time: &EventTime, received: i128) -> Value {
    match time {
        EventTime::Ground => json!({ "kind": "ground", "time": instant_text(received) }),
        EventTime::At(at) => json!({ "kind": "at", "time": instant_text(*at) }),
        EventTime::SinceBoot { value, unit } => {
            json!({ "kind": "since_boot", "value": integer_json(i128::from(*value)), "unit": unit })
        }
        // A message whose event time can't be read is an error case.
        EventTime::Invalid => Value::Null,
    }
}

/// A sample (`spec/api.md` §3.1), with its param's unit from the catalog.
fn sample_json(sample: &Sample, bundle: &Value) -> Value {
    let unit = bundle["catalog"]["params"][&sample.param]
        .get("unit")
        .cloned()
        .unwrap_or(Value::Null);
    json!({
        "param": sample.param,
        "value": expected_json(&sample.value),
        "unit": unit,
        "path": sample.path,
        "index": sample.index.map(|index| integer_json(i128::from(index))),
        "time_offset_ns": sample.time_offset_ns.map(|ns| integer_json(i128::from(ns))),
        "quality": sample.quality,
    })
}

fn engineering_json(engineering: &Engineering) -> Value {
    json!({
        "path": engineering.path,
        "value": expected_json(&engineering.value),
        "quality": engineering.quality,
    })
}

/// A record (`spec/api.md` §3.1): each present entry by name.
fn record_json(record: &[(String, Raw)]) -> Value {
    Value::Object(
        record
            .iter()
            .map(|(name, raw)| (name.clone(), raw_json(raw)))
            .collect(),
    )
}

/// A raw value in `spec/api.md` §1's spelling.
fn raw_json(raw: &Raw) -> Value {
    match raw {
        Raw::Uint(n) => integer_json(i128::from(*n)),
        Raw::Int(n) => integer_json(i128::from(*n)),
        Raw::Float(x) => float_json(*x),
        Raw::Bool(b) => json!(b),
        Raw::Str(text) => json!(text),
        Raw::Bytes(bytes) => json!(hex(bytes)),
        Raw::Array(items) => Value::Array(items.iter().map(raw_json).collect()),
        Raw::Record(fields) => record_json(fields),
        Raw::Null => Value::Null,
    }
}

/// A sample's or engineering value in `spec/api.md` §1's spelling: a
/// vector as its frame and members, a quaternion scalar first.
fn expected_json(value: &Expected) -> Value {
    match value {
        Expected::F64(x) => float_json(*x),
        Expected::I64(n) => integer_json(i128::from(*n)),
        Expected::U64(n) => integer_json(i128::from(*n)),
        Expected::Bool(b) => json!(b),
        Expected::Str(text) | Expected::Enum(text) => json!(text),
        Expected::Bytes(bytes) => json!(hex(bytes)),
        Expected::Vector { frame, members } => {
            let mut vector = Map::new();
            vector.insert("frame".to_string(), json!(frame));
            let names: &[&str] = if members.len() == 4 {
                &["w", "x", "y", "z"]
            } else {
                &["x", "y", "z"]
            };
            for (name, member) in names.iter().zip(members) {
                vector.insert((*name).to_string(), float_json(*member));
            }
            Value::Object(vector)
        }
    }
}

/// A float: a JSON number for a finite one, which serde_json writes with
/// a fraction or an exponent, so it reads back as a float; NaN and the
/// infinities as `spec/api.md` §1's objects.
fn float_json(x: f64) -> Value {
    if x.is_nan() {
        json!({ "non_finite": "NaN" })
    } else if x == f64::INFINITY {
        json!({ "non_finite": "inf" })
    } else if x == f64::NEG_INFINITY {
        json!({ "non_finite": "-inf" })
    } else {
        json!(x)
    }
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

// ---- Encoding cases (`spec/conformance.md` §3) ------------------------------

/// An encoding case file for `commands`: its bundle, a case for each
/// request, with the command it encodes to, and one for each refused
/// request, with its error's code. A refused request that gives a name
/// twice can't be a case, since a case's arguments are an object, which
/// has each name once (`duplicate_argument` can't be written); nor can the
/// payloads with faults planted in them, which test decoding commands
/// (`spec/encoding.md` §7), not in the runtime API.
pub fn encoding_case_file(commands: &Commands, about: &str, origin: &str) -> Value {
    let mut cases: Vec<Value> = commands
        .requests
        .iter()
        .enumerate()
        .map(|(index, request)| encoded_case(commands, request, index, origin))
        .collect();
    cases.extend(
        commands
            .refused
            .iter()
            .enumerate()
            .filter(|(_, refused)| !gives_a_name_twice(&refused.arguments))
            .map(|(index, refused)| refused_case(commands, refused, index, origin)),
    );
    json!({
        "about": about,
        "definitions": commands.bundle,
        "cases": cases,
    })
}

fn gives_a_name_twice(arguments: &[(String, Given)]) -> bool {
    let mut names = BTreeSet::new();
    arguments.iter().any(|(name, _)| !names.insert(name))
}

/// The sections a request's result depends on: arguments, raw values and
/// payloads, and what encoding takes from decoding.md (bits, byte orders,
/// text, positions, checksums, conversion arithmetic) and units.md.
const ENCODED_SPEC: [&str; 10] = [
    "encoding.md §2",
    "encoding.md §3",
    "encoding.md §4",
    "encoding.md §5",
    "encoding.md §6",
    "decoding.md §2",
    "decoding.md §5",
    "decoding.md §7.1",
    "units.md §4",
    "api.md §3.2",
];

/// The sections a refused request's error depends on: the request,
/// arguments, raw values and the codes, and the text and units they take
/// from decoding.md and units.md.
const REFUSED_SPEC: [&str; 6] = [
    "encoding.md §1",
    "encoding.md §2",
    "encoding.md §3",
    "encoding.md §8",
    "decoding.md §2",
    "units.md §4",
];

fn encoded_case(commands: &Commands, request: &Request, index: usize, origin: &str) -> Value {
    let set = commands.bundle["sets"]
        .as_array()
        .and_then(|sets| sets.iter().find(|set| set["name"] == commands.set.as_str()));
    let packet = set
        .and_then(|set| set["commands"].as_array())
        .and_then(|packets| {
            packets
                .iter()
                .find(|packet| packet["canonical"] == request.command.as_str())
        })
        .map_or(Value::Null, |packet| packet["name"].clone());
    let deprecated = commands.bundle["catalog"]["commands"][&request.command]
        .get("deprecated")
        .cloned()
        .unwrap_or(Value::Null);
    let metadata: Map<String, Value> = request
        .metadata
        .iter()
        .map(|(name, value)| (name.clone(), integer_json(i128::from(*value))))
        .collect();
    let encoded = json!({
        "family": commands.family,
        "set": commands.set,
        "packet": packet,
        "command": request.command,
        "payload": hex(&request.payload),
        "metadata": metadata,
        "defaulted": request.defaulted,
        "deprecated": deprecated,
        "record": record_json(&request.record),
    });
    let mut case = Map::new();
    case.insert(
        "name".to_string(),
        json!(format!("request-{index:02}-{}", request.command)),
    );
    case.insert("spec".to_string(), json!(ENCODED_SPEC));
    case.insert(
        "note".to_string(),
        json!(format!(
            "Generated by the testkit's oracle: {origin}, request {index}."
        )),
    );
    case.insert("family".to_string(), json!(commands.family));
    case.insert(
        "request".to_string(),
        request_json(
            &commands.set,
            &request.command,
            &request.arguments,
            request.target.as_ref(),
        ),
    );
    case.insert("encoded".to_string(), encoded);
    Value::Object(case)
}

fn refused_case(commands: &Commands, refused: &Refused, index: usize, origin: &str) -> Value {
    let planted: Vec<String> = refused
        .faults
        .iter()
        .map(|fault| format!("{:?} ({})", fault.kind, fault.code))
        .collect();
    let mut case = Map::new();
    case.insert(
        "name".to_string(),
        json!(format!("refused-{index:02}-{}", refused.code)),
    );
    case.insert("spec".to_string(), json!(REFUSED_SPEC));
    case.insert(
        "note".to_string(),
        json!(format!(
            "Generated by the testkit's oracle: {origin}, refused request {index}. Planted: {}; \
             the first that encoding reaches is the error.",
            planted.join(", ")
        )),
    );
    case.insert("family".to_string(), json!(commands.family));
    case.insert(
        "request".to_string(),
        request_json(
            &refused.set,
            &refused.command,
            &refused.arguments,
            refused.target.as_ref(),
        ),
    );
    case.insert("error".to_string(), json!(refused.code));
    Value::Object(case)
}

/// A request (`spec/conformance.md` §3): each argument tagged with the
/// kind the request gives it as, and the target, if it gives one.
fn request_json(
    set: &str,
    command: &str,
    arguments: &[(String, Given)],
    target: Option<&Target>,
) -> Value {
    let arguments: Map<String, Value> = arguments
        .iter()
        .map(|(name, value)| (name.clone(), tagged(value)))
        .collect();
    let mut request = Map::new();
    request.insert("set".to_string(), json!(set));
    request.insert("command".to_string(), json!(command));
    request.insert("arguments".to_string(), Value::Object(arguments));
    if let Some(target) = target {
        let target = match target {
            Target::Int(n) => integer_json(*n),
            Target::Text(text) => json!(text),
        };
        request.insert("native_id".to_string(), target);
    }
    Value::Object(request)
}

/// A value tagged with its kind (`spec/conformance.md` §3).
fn tagged(value: &Given) -> Value {
    match value {
        Given::Bool(b) => json!({ "boolean": b }),
        Given::Int(n) => json!({ "integer": integer_json(i128::from(*n)) }),
        Given::Uint(n) => json!({ "integer": integer_json(i128::from(*n)) }),
        Given::Float(x) => json!({ "float": float_json(*x) }),
        Given::Text(text) => json!({ "text": text }),
        Given::Bytes(bytes) => json!({ "bytes": hex(bytes) }),
        Given::List(values) => json!({ "list": values.iter().map(tagged).collect::<Vec<Value>>() }),
    }
}

// ---- Command decoding cases (`spec/conformance.md` §4) -----------------------

/// A command decoding case file for `commands`: its bundle, a case for
/// each request's payload and metadata, with the command decoding them
/// gives back, and one for each payload with a fault planted in it, with
/// its error's code. A payload delivered in the encoding other than its
/// family's can't be a case, since an API types each payload by its
/// family (`spec/api.md` §2.7).
pub fn command_decoding_case_file(commands: &Commands, about: &str, origin: &str) -> Value {
    let json_family = commands.bundle["families"][0]["encoding"] == "json";
    let family_encoding = if json_family {
        CommandEncoding::Json
    } else {
        CommandEncoding::Binary
    };
    let mut cases: Vec<Value> = commands
        .requests
        .iter()
        .enumerate()
        .map(|(index, request)| decoded_command_case(commands, request, index, origin))
        .collect();
    cases.extend(
        commands
            .garbled
            .iter()
            .enumerate()
            .filter(|(_, garbled)| garbled.encoding == family_encoding)
            .map(|(index, garbled)| garbled_case(commands, garbled, index, json_family, origin)),
    );
    json!({
        "about": about,
        "definitions": commands.bundle,
        "cases": cases,
    })
}

/// The sections a decoded command depends on: decoding commands, and what
/// it takes from decoding.md, units.md and encoding.md's arguments.
const DECODED_COMMAND_SPEC: [&str; 7] = [
    "encoding.md §7",
    "encoding.md §2",
    "decoding.md §2",
    "decoding.md §5",
    "decoding.md §7.1",
    "units.md §4",
    "api.md §3.5",
];

/// The sections a garbled payload's error depends on.
const GARBLED_SPEC: [&str; 6] = [
    "encoding.md §7",
    "encoding.md §8",
    "decoding.md §2",
    "decoding.md §5",
    "decoding.md §9",
    "units.md §4",
];

fn decoded_command_case(
    commands: &Commands,
    request: &Request,
    index: usize,
    origin: &str,
) -> Value {
    let json_family = commands.bundle["families"][0]["encoding"] == "json";
    let arguments: Map<String, Value> = request
        .decoded
        .arguments
        .iter()
        .map(|(name, value)| (name.clone(), arg_json(value)))
        .collect();
    let target = request
        .decoded
        .target
        .as_ref()
        .map_or(Value::Null, |target| match target {
            Target::Int(n) => integer_json(*n),
            Target::Text(text) => json!(text),
        });
    let decoded = json!({
        "family": commands.family,
        "set": commands.set,
        "packet": packet_of(commands, &request.command),
        "command": request.command,
        "arguments": arguments,
        "defaulted": request.decoded.defaulted,
        "target": target,
        "record": record_json(&request.record),
    });
    let mut case = Map::new();
    case.insert(
        "name".to_string(),
        json!(format!("request-{index:02}-{}", request.command)),
    );
    case.insert("spec".to_string(), json!(DECODED_COMMAND_SPEC));
    case.insert(
        "note".to_string(),
        json!(format!(
            "Generated by the testkit's oracle: {origin}, the payload request {index} encodes to."
        )),
    );
    case.insert("family".to_string(), json!(commands.family));
    case.insert("set".to_string(), json!(commands.set));
    case.insert(
        "message".to_string(),
        command_message(&request.payload, &request.metadata, json_family),
    );
    case.insert("decoded".to_string(), decoded);
    Value::Object(case)
}

fn garbled_case(
    commands: &Commands,
    garbled: &Garbled,
    index: usize,
    json_family: bool,
    origin: &str,
) -> Value {
    let mut case = Map::new();
    case.insert(
        "name".to_string(),
        json!(format!("garbled-{index:02}-{}", garbled.code)),
    );
    case.insert("spec".to_string(), json!(GARBLED_SPEC));
    case.insert(
        "note".to_string(),
        json!(format!(
            "Generated by the testkit's oracle: {origin}, garbled payload {index}. Planted: {}.",
            garbled.planted
        )),
    );
    case.insert("family".to_string(), json!(commands.family));
    case.insert("set".to_string(), json!(garbled.set));
    case.insert(
        "message".to_string(),
        command_message(&garbled.payload, &garbled.metadata, json_family),
    );
    case.insert("error".to_string(), json!(garbled.code));
    Value::Object(case)
}

/// A command message (`spec/conformance.md` §4): a JSON family's payload as
/// text when it's UTF-8, any other as hex, and its metadata.
fn command_message(payload: &[u8], metadata: &[(String, i64)], json_family: bool) -> Value {
    let metadata: Map<String, Value> = metadata
        .iter()
        .map(|(name, value)| (name.clone(), integer_json(i128::from(*value))))
        .collect();
    let mut message = Map::new();
    match std::str::from_utf8(payload) {
        Ok(text) if json_family => message.insert("json".to_string(), json!(text)),
        _ => message.insert("hex".to_string(), json!(hex(payload))),
    };
    message.insert("metadata".to_string(), Value::Object(metadata));
    Value::Object(message)
}

/// The name of the set's packet that encodes `command`.
fn packet_of(commands: &Commands, command: &str) -> Value {
    commands.bundle["sets"]
        .as_array()
        .and_then(|sets| sets.iter().find(|set| set["name"] == commands.set.as_str()))
        .and_then(|set| set["commands"].as_array())
        .and_then(|packets| packets.iter().find(|packet| packet["canonical"] == command))
        .map_or(Value::Null, |packet| packet["name"].clone())
}

/// A decoded argument's value in `spec/api.md` §1's spelling.
fn arg_json(value: &Arg) -> Value {
    match value {
        Arg::Bool(b) => json!(b),
        Arg::I64(n) => integer_json(i128::from(*n)),
        Arg::U64(n) => integer_json(i128::from(*n)),
        Arg::F64(x) => float_json(*x),
        Arg::Text(text) => json!(text),
        Arg::Bytes(bytes) => json!(hex(bytes)),
        Arg::List(values) => Value::Array(values.iter().map(arg_json).collect()),
    }
}
