//! Conformance cases written from the oracle's layouts: decoding cases
//! (`spec/conformance.md` §2), each message of a generated [`Telemetry`]
//! with what [`crate::layout`] works out it decodes to, spelled as
//! `spec/api.md` §1 and §3.1 spell a result; and encoding cases (§3), each
//! request of generated [`Commands`] with the command
//! [`crate::layout::command`] works out it encodes to, spelled as
//! `spec/api.md` §3.2 does, or the error a refused one gives; and command
//! decoding cases (§4), each request's payload with the command decoding
//! gives back (§3.5), and each payload with a fault planted in it with its
//! error. This module
//! spells them itself, never through `mdl`, so a case says what the oracle
//! read in the spec, not what the runtime gives.

use std::collections::BTreeSet;

use serde_json::{Map, Value, json};

use crate::layout::command::{
    Arg, Commands, Encoding as CommandEncoding, Garbled, Given, Refused, Request, Target,
};
use crate::layout::{
    Damage, Encoding, Engineering, EventTime, Expected, Message, Meta, Raw, Sample, Telemetry,
    instant_text, integer_json,
};

/// The largest integer JSON writes as a number (`spec/api.md` §1).
const MAX_SAFE: i128 = (1 << 53) - 1;

/// The asset the case file's one binding names.
const ASSET: &str = "ASSET";

/// A case file for `telemetry`: its bundle, a binding of its native id to
/// its set, and a case for each message a case can hold. It can't hold
/// one delivered in the encoding other than its family's, since an API
/// types each payload by its family (`spec/api.md` §2.2), nor one with a
/// metadata name given twice, since a case's metadata is an object, which
/// has each name once (`spec/decoding.md` §1). `about` says where the
/// layout came from; each case's note names it again (`origin`) with the
/// message's place in it.
pub fn case_file(telemetry: &Telemetry, about: &str, origin: &str) -> Value {
    let json_family = telemetry.bundle["families"][0]["encoding"] == "json";
    let family_encoding = if json_family {
        Encoding::Json
    } else {
        Encoding::Binary
    };
    let cases: Vec<Value> = telemetry
        .messages
        .iter()
        .enumerate()
        .filter(|(_, message)| {
            message.encoding == family_encoding && !repeats_a_name(&message.metadata)
        })
        .map(|(index, message)| case(telemetry, message, index, json_family, origin))
        .collect();
    json!({
        "about": about,
        "definitions": telemetry.bundle,
        "bindings": bindings(telemetry),
        "cases": cases,
    })
}

/// Whether a metadata name is given more than once.
fn repeats_a_name(metadata: &[(String, Meta)]) -> bool {
    let mut names = BTreeSet::new();
    metadata.iter().any(|(name, _)| !names.insert(name))
}

/// The bindings file the property tests decode the layout's messages
/// with, as its lines: the native id bound to the set from the GPS epoch
/// on, before any generated ground time.
fn bindings(telemetry: &Telemetry) -> Vec<String> {
    let native_id = match integer_spelled(&telemetry.native_id) {
        Some(n) if n.abs() <= MAX_SAFE => n.to_string(),
        _ => Value::from(telemetry.native_id.as_str()).to_string(),
    };
    vec![
        "mdl_version = \"2.0\"".to_string(),
        String::new(),
        "[[binding]]".to_string(),
        format!("family = {}", Value::from(telemetry.family.as_str())),
        format!("native_id = {native_id}"),
        format!("asset = {}", Value::from(ASSET)),
        format!("set = {}", Value::from(telemetry.set.as_str())),
        "effective_from = \"1980-01-06T00:00:00Z\"".to_string(),
    ]
}

fn case(
    telemetry: &Telemetry,
    message: &Message,
    index: usize,
    json_family: bool,
    origin: &str,
) -> Value {
    let mut note = format!(
        "Generated by the testkit's oracle: {origin}, message {index}, of packet {}.",
        message.packet
    );
    let (spec, outcome) = match &message.damage {
        Some(Damage {
            planted, failure, ..
        }) => {
            note.push_str(&format!(" Planted: {planted}."));
            (
                damaged_spec(json_family),
                ("error", json!(failure.problem.code())),
            )
        }
        None if message.event_time == EventTime::Invalid => {
            note.push_str(" Its event time can't be read.");
            (damaged_spec(json_family), ("error", json!("invalid_time")))
        }
        None => (
            decoded_spec(json_family),
            ("decoded", decoded(telemetry, message)),
        ),
    };
    let payload = match std::str::from_utf8(&message.payload) {
        Ok(text) if json_family => ("json", json!(text)),
        _ => ("hex", json!(hex(&message.payload))),
    };
    let metadata: Map<String, Value> = message
        .metadata
        .iter()
        .map(|(name, value)| {
            let value = match value {
                Meta::Uint(n) => integer_json(i128::from(*n)),
                Meta::Int(n) => integer_json(i128::from(*n)),
                Meta::Text(text) => json!(text),
            };
            (name.clone(), value)
        })
        .collect();
    let mut message_json = Map::new();
    message_json.insert(payload.0.to_string(), payload.1);
    message_json.insert("metadata".to_string(), Value::Object(metadata));
    message_json.insert(
        "ground_time".to_string(),
        json!(instant_text(message.received)),
    );
    let mut case = Map::new();
    case.insert(
        "name".to_string(),
        json!(format!("{index:02}-{}", message.packet)),
    );
    case.insert("spec".to_string(), json!(spec));
    case.insert("note".to_string(), json!(note));
    case.insert("family".to_string(), json!(telemetry.family));
    case.insert("message".to_string(), Value::Object(message_json));
    case.insert(outcome.0.to_string(), outcome.1);
    Value::Object(case)
}

/// The sections a message's result depends on: its values, routing,
/// identification, extraction (checksums included), record, meaning and
/// event time.
fn decoded_spec(json_family: bool) -> Vec<&'static str> {
    let values = if json_family {
        &["decoding.md §2.3"][..]
    } else {
        &["decoding.md §2.1", "decoding.md §2.2"][..]
    };
    let mut spec = values.to_vec();
    spec.extend([
        "decoding.md §3",
        "decoding.md §4",
        "decoding.md §5",
        "decoding.md §6",
        "decoding.md §7",
        "decoding.md §8",
        "api.md §3.1",
    ]);
    spec
}

